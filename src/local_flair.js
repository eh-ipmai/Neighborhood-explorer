/**
 * Automatically detect the most vivid, affectionate Local Flair profile for any real-world
 * city, borough, country, coordinate, or biome!
 */
export function detectLocalFlair({
  lat = null,
  lon = null,
  countryCode = "",
  townName = "",
  address = "",
  biomeId = "",
  preset = "",
  explicitFlair = "",
} = {}) {
  if (explicitFlair && LOCAL_FLAIR_PROFILES[explicitFlair]) {
    return explicitFlair;
  }
  if (preset === "newton") {
    return "boston_new_england";
  }

  const cc = String(countryCode || "").trim().toLowerCase();
  const blob = `${townName || ""} ${address || ""}`.toLowerCase();
  const hasCoord =
    typeof lat === "number" &&
    typeof lon === "number" &&
    Number.isFinite(lat) &&
    Number.isFinite(lon);

  // 1. Brooklyn & NYC (Hasidic neighbors, hipsters, pizza & bagel locals!)
  const inNycMetroBox =
    hasCoord && lat >= 40.54 && lat <= 40.88 && lon >= -74.06 && lon <= -73.76;
  if (
    /\b(brooklyn|crown heights|williamsburg|borough park|boro park|midwood|flatbush|park slope|bushwick|bed-?stuy|dumbo|greenpoint|brooklyn heights|new york|manhattan|queens|bronx|nyc|staten island|monsey|lakewood)\b/.test(
      blob
    ) ||
    inNycMetroBox
  ) {
    return "brooklyn_nyc";
  }

  // 2. France (Paris, Lyon, Marseille, Bordeaux, Nice, Normandy, cc=fr)
  if (
    cc === "fr" ||
    /\b(paris|lyon|marseille|bordeaux|nice|toulouse|strasbourg|montmartre|champs-?elys|rivoli|france)\b/.test(
      blob
    )
  ) {
    return "paris_france";
  }

  // 3. New Orleans / Louisiana
  if (
    /\b(new orleans|nola|french quarter|bourbon st|louisiana|baton rouge)\b/.test(blob) ||
    (hasCoord && lat >= 29.86 && lat <= 30.08 && lon >= -90.22 && lon <= -89.9)
  ) {
    return "new_orleans_jazz";
  }

  // 4. UK & Ireland (London, Oxford, Edinburgh, Dublin, Manchester)
  if (
    cc === "gb" ||
    cc === "uk" ||
    cc === "ie" ||
    /\b(london|england|scotland|wales|ireland|dublin|edinburgh|oxford|cambridge.*uk|manchester|liverpool|baker st)\b/.test(
      blob
    )
  ) {
    return "london_uk";
  }

  // 5. Italy (Rome, Florence, Venice, Milan, Naples, Sicily)
  if (
    cc === "it" ||
    /\b(rome|roma|italy|italia|florence|firenze|venice|venezia|milan|milano|naples|napoli|bologna|sicily|tuscany)\b/.test(
      blob
    )
  ) {
    return "italy_rome";
  }

  // 6. Japan (Tokyo, Kyoto, Osaka, Hokkaido, Sapporo, Okinawa)
  if (
    cc === "jp" ||
    /\b(tokyo|kyoto|osaka|japan|shibuya|shinjuku|asakusa|harajuku|yokohama|sapporo|nara|hiroshima)\b/.test(
      blob
    )
  ) {
    return "tokyo_japan";
  }

  // 7. South Korea (Seoul, Busan, Jeju)
  if (
    cc === "kr" ||
    /\b(seoul|korea|busan|incheon|gangnam|hongdae|myeongdong|jeju)\b/.test(blob)
  ) {
    return "seoul_korea";
  }

  // 8. Israel (Jerusalem/Hills vs Tel Aviv/Coast)
  if (
    biomeId === "israel_jerusalem" ||
    biomeId === "israel_galilee" ||
    /\b(jerusalem|beit shemesh|efrat|tzfat|safed|bnei brak|modi'in|modiin)\b/.test(blob) ||
    /ירושלים|בית שמש|צפת|בני ברק|אפרת/.test(blob)
  ) {
    return "jerusalem_israel";
  }
  if (
    biomeId === "israel_coastal" ||
    biomeId === "israel_desert" ||
    cc === "il" ||
    /\b(tel aviv|jaffa|yafo|herzliya|haifa|netanya|ra'anana|raanana|eilat|beer sheva|israel)\b/.test(
      blob
    ) ||
    /תל אביב|יפו|חיפה|רעננה|אילת|ישראל/.test(blob)
  ) {
    return "tel_aviv_israel";
  }

  // 9. Mexico & Latin Plaza (Mexico, Puerto Rico, Costa Rica, Colombia, Argentina, Spain)
  if (
    ["mx", "es", "co", "ar", "pe", "cl", "gt", "ec", "cr", "cu", "do", "pr"].includes(cc) ||
    /\b(mexico|oaxaca|cancun|guadalajara|tijuana|madrid|barcelona|seville|buenos aires|bogota|san juan)\b/.test(
      blob
    )
  ) {
    return "mexico_latin";
  }

  // 10. Germany, Austria, Switzerland (Alpine Pretzels & Konditorei)
  if (
    ["de", "at", "ch", "li"].includes(cc) ||
    biomeId === "alpine" ||
    /\b(munich|münchen|berlin|vienna|wien|zurich|zürich|salzburg|innsbruck|bavaria|germany|austria|switzerland|zermatt|frankfurt|hamburg)\b/.test(
      blob
    )
  ) {
    return "germany_alpine";
  }

  // 11. Nordic & Arctic (Norway, Sweden, Denmark, Finland, Iceland, Tundra)
  if (
    ["no", "se", "dk", "fi", "is", "gl", "sj"].includes(cc) ||
    biomeId === "tundra" ||
    /\b(oslo|stockholm|copenhagen|helsinki|reykjavik|norway|sweden|denmark|finland|iceland|bergen|gothenburg|troms)\b/.test(
      blob
    )
  ) {
    return "nordic_arctic";
  }

  // 12. Texas & US Southwest (Cowboy Hats, Tacos & Guitars)
  if (
    biomeId === "southwest_desert" ||
    /\b(texas|austin|dallas|houston|san antonio|fort worth|el paso|phoenix|tucson|scottsdale|santa fe|albuquerque|sedona|arizona|new mexico|nashville)\b/.test(
      blob
    ) ||
    /,\s*(tx|az|nm|ok)\b/.test(blob) ||
    (cc === "us" &&
      hasCoord &&
      lat >= 25.8 &&
      lat <= 37.0 &&
      lon >= -115.0 &&
      lon <= -93.5)
  ) {
    return "texas_southwest";
  }

  // 13. California, Hawaii, Miami & Tropical Coasts
  if (
    biomeId === "tropical_coastal" ||
    /\b(california|los angeles|san francisco|san diego|santa monica|venice beach|malibu|honolulu|maui|hawaii|miami|key west|bali|phuket)\b/.test(
      blob
    ) ||
    /,\s*(ca|hi)\b/.test(blob) ||
    (cc === "us" && hasCoord && lat >= 32.5 && lat <= 38.5 && lon >= -123.5 && lon <= -116.5)
  ) {
    return "california_tropical";
  }

  // 14. Boston / New England
  if (
    biomeId === "new_england_autumn" ||
    /\b(boston|newton|brookline|cambridge|somerville|massachusetts|vermont|maine|new hampshire|rhode island|connecticut|providence|portland.*me)\b/.test(
      blob
    ) ||
    /,\s*(ma|vt|nh|me|ri|ct)\b/.test(blob)
  ) {
    return "boston_new_england";
  }

  // 15. General European Historic fallback
  if (biomeId === "european_historic") {
    return "european_classic";
  }

  // 16. General East Asian Urban fallback
  if (biomeId === "east_asian_urban") {
    return "tokyo_japan";
  }

  return "neighborhood_classic";
}

/**
 * Get the full Local Flair configuration object (resolved from an ID or a worldMap/meta object).
 */
export function getLocalFlairProfile(idOrWorldMap = null) {
  if (typeof idOrWorldMap === "string") {
    return LOCAL_FLAIR_PROFILES[idOrWorldMap] || LOCAL_FLAIR_PROFILES.neighborhood_classic;
  }
  if (idOrWorldMap && typeof idOrWorldMap === "object") {
    if (idOrWorldMap.id && LOCAL_FLAIR_PROFILES[idOrWorldMap.id]) {
      return LOCAL_FLAIR_PROFILES[idOrWorldMap.id];
    }
    const id = detectLocalFlair({
      lat: idOrWorldMap.origin?.lat ?? idOrWorldMap.lat,
      lon: idOrWorldMap.origin?.lon ?? idOrWorldMap.lon,
      countryCode: idOrWorldMap.meta?.countryCode ?? idOrWorldMap.countryCode ?? "",
      townName: idOrWorldMap.meta?.townName ?? idOrWorldMap.townName ?? "",
      address:
        idOrWorldMap.meta?.homeAddress ??
        idOrWorldMap.origin?.address ??
        idOrWorldMap.origin?.name ??
        idOrWorldMap.address ??
        "",
      biomeId: idOrWorldMap.meta?.biome ?? idOrWorldMap.biome ?? idOrWorldMap.biomeId ?? "",
      preset: idOrWorldMap.meta?.preset ?? idOrWorldMap.preset ?? "",
      explicitFlair: idOrWorldMap.meta?.localFlair ?? idOrWorldMap.localFlair ?? "",
    });
    return LOCAL_FLAIR_PROFILES[id] || LOCAL_FLAIR_PROFILES.neighborhood_classic;
  }
  return LOCAL_FLAIR_PROFILES.neighborhood_classic;
}

/**
 * Substitute `{CITY}` cleanly into regional chant arrays.
 */
export function formatLocalFlairChants(chants = [], cityShort = "Town") {
  const city = String(cityShort || "TOWN").toUpperCase().slice(0, 10);
  return (chants || []).map((c) => String(c).replace(/\{CITY\}/g, city));
}
